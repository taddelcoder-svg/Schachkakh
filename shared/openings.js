const MAP = new Map(LIST);

export function openingName(sanList) {
  let name = null;
  for (let n = 1; n <= Math.min(sanList.length, 12); n++) {
    const key = sanList.slice(0, n).join(' ');
    if (MAP.has(key)) name = MAP.get(key);
  }
  return name;
}
